-- GASTOS DE VEHÍCULOS del CEA · combustible, reparaciones, llantas, etc. por vehículo.
-- Ejecutar UNA sola vez, conectado como CEA_APP, como script (F5 en SQL Developer).

DECLARE
    cantidad NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CEA_APP' THEN
        RAISE_APPLICATION_ERROR(-21101, 'Conéctate como CEA_APP para ejecutar esta migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tables WHERE table_name = 'GASTOS_VEHICULOS';
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-21102, 'GASTOS_VEHICULOS ya existe; revisa si la migración ya se aplicó.');
    END IF;
END;
/

CREATE TABLE gastos_vehiculos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vehiculo VARCHAR2(40) NOT NULL,
    tipo VARCHAR2(30) NOT NULL,
    valor NUMBER(12,0) NOT NULL,
    fecha DATE NOT NULL,
    nota VARCHAR2(200),
    usuario_id NUMBER,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_gastos_vehiculos PRIMARY KEY (id),
    CONSTRAINT ck_gastos_veh_valor CHECK (valor > 0),
    CONSTRAINT fk_gastos_veh_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX ix_gastos_veh_fecha ON gastos_vehiculos (fecha, vehiculo);

GRANT SELECT, INSERT, UPDATE, DELETE ON CEA_APP.GASTOS_VEHICULOS TO CEA_WEB;

COMMIT;