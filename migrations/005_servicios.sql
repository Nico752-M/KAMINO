-- TIENDA · Servicios (trámites, SOAT, peritajes, asesorías…) con sus requisitos editables.
-- Ejecutar UNA sola vez, conectado como el usuario de Oracle de la tienda (CEA_JAMES), como script.
-- Compatible con SQL Developer Web (Database Actions): no usa comandos restringidos como WHENEVER.
-- No toca productos ni ventas anteriores: solo agrega tablas y deja opcional el producto de cada ítem.

CREATE SEQUENCE t_seq_servicios START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE t_servicios (
    id NUMBER NOT NULL,
    nombre VARCHAR2(80) NOT NULL,
    categoria VARCHAR2(40) DEFAULT 'General' NOT NULL,
    precio NUMBER(12,0) DEFAULT 0 NOT NULL,
    costo_terceros NUMBER(12,0) DEFAULT 0 NOT NULL,   -- lo que se le paga a la aseguradora, al tránsito, etc.
    precio_variable NUMBER(1,0) DEFAULT 0 NOT NULL,   -- 1 = el precio se escribe al cobrar
    activo NUMBER(1,0) DEFAULT 1 NOT NULL,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_t_servicios PRIMARY KEY (id),
    CONSTRAINT ck_t_srv_precio CHECK (precio >= 0),
    CONSTRAINT ck_t_srv_terceros CHECK (costo_terceros >= 0),
    CONSTRAINT ck_t_srv_variable CHECK (precio_variable IN (0, 1)),
    CONSTRAINT ck_t_srv_activo CHECK (activo IN (0, 1))
);

CREATE INDEX ix_t_servicios_activo ON t_servicios (activo, categoria, nombre);

CREATE TABLE t_servicio_requisitos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    servicio_id NUMBER NOT NULL,
    tipo VARCHAR2(10) NOT NULL,                       -- DOCUMENTO (lista de chequeo) o DATO (se anota al cobrar)
    texto VARCHAR2(80) NOT NULL,
    obligatorio NUMBER(1,0) DEFAULT 0 NOT NULL,
    orden NUMBER(4,0) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_t_srv_req PRIMARY KEY (id),
    CONSTRAINT fk_t_srv_req_srv FOREIGN KEY (servicio_id) REFERENCES t_servicios (id),
    CONSTRAINT ck_t_srv_req_tipo CHECK (tipo IN ('DOCUMENTO', 'DATO')),
    CONSTRAINT ck_t_srv_req_oblig CHECK (obligatorio IN (0, 1))
);

CREATE INDEX ix_t_srv_req_srv ON t_servicio_requisitos (servicio_id, orden);

-- Cada ítem de una venta es un producto O un servicio (exactamente uno de los dos).
ALTER TABLE t_venta_items MODIFY (producto_id NULL);
ALTER TABLE t_venta_items ADD (servicio_id NUMBER, detalle VARCHAR2(500));
ALTER TABLE t_venta_items ADD CONSTRAINT fk_t_items_servicio FOREIGN KEY (servicio_id) REFERENCES t_servicios (id);
ALTER TABLE t_venta_items ADD CONSTRAINT ck_t_items_uno CHECK (
    (producto_id IS NOT NULL AND servicio_id IS NULL) OR (producto_id IS NULL AND servicio_id IS NOT NULL));
CREATE INDEX ix_t_items_servicio ON t_venta_items (servicio_id);

