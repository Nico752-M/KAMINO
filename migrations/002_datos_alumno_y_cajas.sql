-- Ejecutar una sola vez conectado como propietario CEA_APP, después de 001.
-- Conserva los registros existentes; los datos históricos quedan con caja_id NULL.

SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    cantidad NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CEA_APP' THEN
        RAISE_APPLICATION_ERROR(-20101, 'Conéctate como CEA_APP para ejecutar esta migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM all_users WHERE username = 'CEA_WEB';
    IF cantidad = 0 THEN
        RAISE_APPLICATION_ERROR(-20102, 'No existe el usuario de aplicación CEA_WEB.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tables WHERE table_name = 'CAJAS';
    IF cantidad > 0 THEN
        RAISE_APPLICATION_ERROR(-20103, 'La migración ya se aplicó parcialmente o CAJAS ya existe.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tables
    WHERE table_name IN ('ALUMNOS', 'MATRICULAS', 'PAGOS', 'INGRESOS_CAJA', 'SALIDAS_CAJA');
    IF cantidad <> 5 THEN
        RAISE_APPLICATION_ERROR(-20104, 'Falta una o más tablas base requeridas.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tab_columns
    WHERE (table_name = 'ALUMNOS' AND column_name IN
        ('TIPO_DOCUMENTO', 'FECHA_NACIMIENTO', 'LUGAR_NACIMIENTO', 'SEXO',
         'ESTADO_CIVIL', 'GRUPO_SANGUINEO', 'OCUPACION', 'CELULAR', 'EMAIL'))
       OR (table_name = 'MATRICULAS' AND column_name IN
        ('PRECIO_BASE', 'DESCUENTO_VALOR', 'DESCUENTO_PORCENTAJE'))
       OR (table_name IN ('PAGOS', 'INGRESOS_CAJA', 'SALIDAS_CAJA') AND column_name = 'CAJA_ID');
    IF cantidad > 0 THEN
        RAISE_APPLICATION_ERROR(-20105, 'Se encontraron columnas de esta migración; revisa el estado antes de continuar.');
    END IF;
END;
/

ALTER TABLE alumnos ADD (
    tipo_documento VARCHAR2(20),
    fecha_nacimiento DATE,
    lugar_nacimiento VARCHAR2(120),
    sexo VARCHAR2(20),
    estado_civil VARCHAR2(30),
    grupo_sanguineo VARCHAR2(5),
    ocupacion VARCHAR2(120),
    celular VARCHAR2(30),
    email VARCHAR2(254)
);

ALTER TABLE matriculas ADD (
    precio_base NUMBER(12,0),
    descuento_valor NUMBER(12,0) DEFAULT 0 NOT NULL,
    descuento_porcentaje NUMBER(5,2) DEFAULT 0 NOT NULL
);

UPDATE matriculas
SET precio_base = precio_total
WHERE precio_base IS NULL;

ALTER TABLE matriculas MODIFY (precio_base NOT NULL);
ALTER TABLE matriculas ADD CONSTRAINT ck_mat_descuento_valor
    CHECK (descuento_valor >= 0);
ALTER TABLE matriculas ADD CONSTRAINT ck_mat_descuento_pct
    CHECK (descuento_porcentaje BETWEEN 0 AND 100);

CREATE TABLE responsables_matricula (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_matricula NUMBER NOT NULL,
    tipo_documento VARCHAR2(20) NOT NULL,
    numero_documento VARCHAR2(20) NOT NULL,
    nombres VARCHAR2(100) NOT NULL,
    apellidos VARCHAR2(100) NOT NULL,
    celular VARCHAR2(30),
    email VARCHAR2(254),
    relacion VARCHAR2(40) NOT NULL,
    CONSTRAINT pk_resp_matricula PRIMARY KEY (id),
    CONSTRAINT uq_resp_matricula UNIQUE (id_matricula),
    CONSTRAINT fk_resp_matricula FOREIGN KEY (id_matricula)
        REFERENCES matriculas (id) ON DELETE CASCADE
);

CREATE TABLE cajas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    usuario_id NUMBER NOT NULL,
    fecha_apertura TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    monto_apertura NUMBER(12,0) DEFAULT 0 NOT NULL,
    estado VARCHAR2(10) DEFAULT 'ABIERTA' NOT NULL,
    fecha_cierre TIMESTAMP,
    monto_cierre NUMBER(12,0),
    efectivo_esperado NUMBER(12,0),
    diferencia NUMBER(12,0),
    observaciones_cierre VARCHAR2(1000),
    CONSTRAINT pk_cajas PRIMARY KEY (id),
    CONSTRAINT fk_cajas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_cajas_estado CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT ck_cajas_apertura CHECK (monto_apertura >= 0),
    CONSTRAINT ck_cajas_cierre CHECK (monto_cierre IS NULL OR monto_cierre >= 0)
);

-- Oracle permite una sola caja abierta por cajero mediante este índice funcional.
CREATE UNIQUE INDEX uq_cajas_abierta_usuario
    ON cajas (CASE WHEN estado = 'ABIERTA' THEN usuario_id END);

ALTER TABLE pagos ADD (caja_id NUMBER);
ALTER TABLE pagos ADD CONSTRAINT fk_pagos_caja
    FOREIGN KEY (caja_id) REFERENCES cajas (id);

ALTER TABLE ingresos_caja ADD (caja_id NUMBER);
ALTER TABLE ingresos_caja ADD CONSTRAINT fk_ingresos_caja_sesion
    FOREIGN KEY (caja_id) REFERENCES cajas (id);

ALTER TABLE salidas_caja ADD (caja_id NUMBER);
ALTER TABLE salidas_caja ADD CONSTRAINT fk_salidas_caja_sesion
    FOREIGN KEY (caja_id) REFERENCES cajas (id);

CREATE INDEX ix_pagos_caja ON pagos (caja_id);
CREATE INDEX ix_ingresos_caja_sesion ON ingresos_caja (caja_id);
CREATE INDEX ix_salidas_caja_sesion ON salidas_caja (caja_id);
CREATE INDEX ix_cajas_fecha_usuario ON cajas (fecha_apertura, usuario_id);
CREATE INDEX ix_resp_matricula_doc ON responsables_matricula (numero_documento);

