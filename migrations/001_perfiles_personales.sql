-- Ejecutar una sola vez conectado como propietario CEA_APP.
-- Cada perfil pertenece a una única persona; USUARIOS.ROL se conserva
-- como categoría heredada, pero los permisos efectivos salen del perfil.

SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    cantidad NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CEA_APP' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Conéctate como CEA_APP para ejecutar esta migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM all_users WHERE username = 'CEA_WEB';
    IF cantidad = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'No existe el usuario de aplicación CEA_WEB.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tables
    WHERE table_name IN ('PERFILES', 'PERFIL_PERMISOS');
    IF cantidad > 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'La migración ya se aplicó parcialmente o las tablas ya existen.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tab_columns
    WHERE table_name = 'SALIDAS_CAJA' AND column_name = 'NUMERO_RECIBO';
    IF cantidad > 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'SALIDAS_CAJA.NUMERO_RECIBO ya existe; revisa el estado de la migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tables WHERE table_name = 'SALIDAS_CAJA';
    IF cantidad = 0 THEN
        RAISE_APPLICATION_ERROR(-20005, 'No existe la tabla SALIDAS_CAJA.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM all_cons_columns
    WHERE owner = 'CEA_APP' AND constraint_name = 'UQ_MAT_ORDEN'
      AND ((column_name = 'ANIO' AND position = 1)
        OR (column_name = 'NUMERO_ORDEN' AND position = 2));
    IF cantidad <> 2 THEN
        RAISE_APPLICATION_ERROR(-20006, 'UQ_MAT_ORDEN debe ser (ANIO, NUMERO_ORDEN).');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM all_constraints
    WHERE owner = 'CEA_APP' AND constraint_name = 'UQ_MAT_ORDEN'
      AND constraint_type = 'U' AND status = 'ENABLED';
    IF cantidad <> 1 THEN
        RAISE_APPLICATION_ERROR(-20007, 'UQ_MAT_ORDEN debe estar habilitada como restricción UNIQUE.');
    END IF;
END;
/

CREATE TABLE perfiles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    usuario_id NUMBER NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_perfiles PRIMARY KEY (id),
    CONSTRAINT uq_perfiles_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_perfiles_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
);

CREATE TABLE perfil_permisos (
    perfil_id NUMBER NOT NULL,
    codigo VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_perfil_permisos PRIMARY KEY (perfil_id, codigo),
    CONSTRAINT fk_pp_perfil FOREIGN KEY (perfil_id)
        REFERENCES perfiles (id) ON DELETE CASCADE
);

ALTER TABLE salidas_caja ADD (numero_recibo VARCHAR2(50));
ALTER TABLE salidas_caja ADD CONSTRAINT uq_salidas_recibo UNIQUE (numero_recibo);

INSERT INTO perfiles (usuario_id, nombre)
SELECT id, SUBSTR(nombre || ' - ' || INITCAP(rol), 1, 100)
FROM usuarios;

-- Todos conservan el acceso de consulta que ya tenían.
INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, permisos.codigo
FROM perfiles pf
CROSS JOIN (
    SELECT 'ver_dashboard' AS codigo FROM dual UNION ALL
    SELECT 'ver_alumnos' FROM dual UNION ALL
    SELECT 'ver_caja' FROM dual UNION ALL
    SELECT 'ver_tramites' FROM dual UNION ALL
    SELECT 'ver_recibos' FROM dual
) permisos;

-- Se mantienen los permisos de cobro y RUNT que ya correspondían a cada rol.
INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, 'registrar_pagos'
FROM perfiles pf JOIN usuarios u ON u.id = pf.usuario_id
WHERE u.rol IN ('admin', 'cajera', 'secretaria');

INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, 'marcar_runt'
FROM perfiles pf JOIN usuarios u ON u.id = pf.usuario_id
WHERE u.rol IN ('admin', 'secretaria');

-- Las funciones nuevas quedan inicialmente solo para administración.
INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, permisos.codigo
FROM perfiles pf JOIN usuarios u ON u.id = pf.usuario_id
CROSS JOIN (
    SELECT 'crear_matricula' AS codigo FROM dual UNION ALL
    SELECT 'gestionar_caja' FROM dual UNION ALL
    SELECT 'gestionar_usuarios' FROM dual
) permisos
WHERE u.rol = 'admin';

GRANT SELECT, INSERT, UPDATE ON CEA_APP.USUARIOS TO CEA_WEB;
GRANT SELECT, INSERT, UPDATE ON CEA_APP.PERFILES TO CEA_WEB;
GRANT SELECT, INSERT, UPDATE, DELETE ON CEA_APP.PERFIL_PERMISOS TO CEA_WEB;
GRANT SELECT, INSERT ON CEA_APP.INGRESOS_CAJA TO CEA_WEB;
GRANT SELECT, INSERT ON CEA_APP.SALIDAS_CAJA TO CEA_WEB;

COMMIT;
PROMPT Migración de perfiles personales aplicada correctamente.
