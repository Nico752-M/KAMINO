CREATE TABLE auditoria_cambios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    entidad VARCHAR2(30) NOT NULL,
    entidad_id NUMBER NOT NULL,
    accion VARCHAR2(30) NOT NULL,
    usuario_id NUMBER NOT NULL,
    antes CLOB,
    despues CLOB,
    motivo VARCHAR2(500),
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_auditoria_cambios PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX ix_auditoria_entidad_fecha
    ON auditoria_cambios (entidad, entidad_id, fecha);

CREATE TABLE reimpresiones_recibos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tipo VARCHAR2(20) NOT NULL,
    numero_recibo VARCHAR2(50) NOT NULL,
    usuario_id NUMBER NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_reimpresiones_recibos PRIMARY KEY (id),
    CONSTRAINT ck_reimpresion_tipo CHECK (tipo IN ('PAGO', 'INGRESO', 'EGRESO')),
    CONSTRAINT fk_reimpresion_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX ix_reimpresiones_numero
    ON reimpresiones_recibos (numero_recibo, fecha);

DECLARE
    siguiente NUMBER;
BEGIN
    SELECT NVL(MAX(
        CASE WHEN REGEXP_LIKE(numero_recibo, '^CEA-[0-9]{6}$')
             THEN TO_NUMBER(SUBSTR(numero_recibo, 5))
        END
    ), 0) + 1
    INTO siguiente
    FROM (
        SELECT numero_recibo FROM pagos
        UNION ALL
        SELECT numero_recibo FROM ingresos_caja
        UNION ALL
        SELECT numero_recibo FROM salidas_caja
    );

    EXECUTE IMMEDIATE
        'CREATE SEQUENCE seq_recibos START WITH ' ||
        TO_CHAR(siguiente, 'FM9999999999999999999999999999999999999999') ||
        ' INCREMENT BY 1 NOCYCLE CACHE 20';
END;
/

INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, permisos.codigo
FROM perfiles pf
JOIN usuarios u ON u.id = pf.usuario_id
CROSS JOIN (
    SELECT 'editar_alumnos' AS codigo FROM dual UNION ALL
    SELECT 'eliminar_alumnos' FROM dual UNION ALL
    SELECT 'ver_historial_pagos' FROM dual
) permisos
WHERE u.rol = 'admin';

