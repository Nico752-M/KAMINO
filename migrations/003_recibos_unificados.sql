-- Ejecutar una sola vez conectado como propietario CEA_APP, después de 001 y 002.
-- Conserva los recibos existentes; la secuencia continúa desde los CEA-000000 existentes.

SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    cantidad NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CEA_APP' THEN
        RAISE_APPLICATION_ERROR(-20201, 'Conéctate como CEA_APP para ejecutar esta migración.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM all_users WHERE username = 'CEA_WEB';
    IF cantidad = 0 THEN
        RAISE_APPLICATION_ERROR(-20202, 'No existe el usuario de aplicación CEA_WEB.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tables
    WHERE table_name IN ('USUARIOS', 'PERFILES', 'PERFIL_PERMISOS', 'ALUMNOS',
                         'MATRICULAS', 'PAGOS', 'INGRESOS_CAJA', 'SALIDAS_CAJA',
                         'RESPONSABLES_MATRICULA', 'CAJAS');
    IF cantidad <> 10 THEN
        RAISE_APPLICATION_ERROR(-20203, 'Faltan tablas base; aplica primero las migraciones 001 y 002.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tab_columns
    WHERE table_name IN ('PAGOS', 'INGRESOS_CAJA', 'SALIDAS_CAJA')
      AND column_name = 'NUMERO_RECIBO';
    IF cantidad <> 3 THEN
        RAISE_APPLICATION_ERROR(-20204, 'Falta NUMERO_RECIBO en una tabla de movimientos.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tab_columns
    WHERE table_name IN ('PAGOS', 'INGRESOS_CAJA', 'SALIDAS_CAJA')
      AND column_name IN ('ANULADO', 'MOTIVO_ANULACION', 'ANULADO_POR', 'FECHA_ANULACION');
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20205, 'Se encontraron columnas de anulación; revisa si la migración ya se aplicó.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tab_columns
    WHERE table_name = 'MATRICULAS'
      AND column_name IN ('ARCHIVADO', 'MOTIVO_ARCHIVO', 'ARCHIVADO_POR', 'FECHA_ARCHIVO');
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20209, 'Se encontraron columnas de archivo; revisa el estado de la migración.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tables
    WHERE table_name IN ('AUDITORIA_CAMBIOS', 'REIMPRESIONES_RECIBOS');
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20206, 'Se encontraron tablas de auditoría/reimpresión; revisa el estado de la migración.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_sequences WHERE sequence_name = 'SEQ_RECIBOS';
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20207, 'SEQ_RECIBOS ya existe; revisa el estado de la migración.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM perfil_permisos
    WHERE codigo IN ('editar_alumnos', 'eliminar_alumnos', 'ver_historial_pagos');
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20208, 'Los permisos nuevos ya existen; revisa el estado de la migración.');
    END IF;
END;
/

