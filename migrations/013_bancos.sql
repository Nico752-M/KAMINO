-- BANCOS · bancos, bolsillos y libro de movimientos bancarios.
-- Ejecutar UNA sola vez, conectado como CEA_APP, después de la 012.

DECLARE
    cantidad NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CEA_APP' THEN
        RAISE_APPLICATION_ERROR(-21301, 'Conéctate como CEA_APP para ejecutar esta migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tables
    WHERE table_name IN ('BANCOS', 'BOLSILLOS', 'MOVIMIENTOS_BANCO');
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-21302, 'Las tablas de bancos ya existen; revisa si la migración ya se aplicó.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM user_tab_columns
    WHERE table_name IN ('INGRESOS_CAJA', 'SALIDAS_CAJA') AND column_name = 'ES_TRASLADO';
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-21303, 'ES_TRASLADO ya existe; revisa si la migración ya se aplicó.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM perfil_permisos
    WHERE codigo IN ('ver_bancos', 'gestionar_bancos');
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-21304, 'Los permisos de bancos ya existen.');
    END IF;
END;
/

CREATE TABLE bancos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(60) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_bancos PRIMARY KEY (id),
    CONSTRAINT uq_bancos_nombre UNIQUE (nombre),
    CONSTRAINT ck_bancos_activo CHECK (activo IN (0, 1))
);

CREATE TABLE bolsillos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    banco_id NUMBER NOT NULL,
    nombre VARCHAR2(60) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_bolsillos PRIMARY KEY (id),
    CONSTRAINT uq_bolsillos_nombre UNIQUE (banco_id, nombre),
    CONSTRAINT fk_bolsillos_banco FOREIGN KEY (banco_id) REFERENCES bancos (id),
    CONSTRAINT ck_bolsillos_activo CHECK (activo IN (0, 1))
);

CREATE TABLE movimientos_banco (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    banco_id NUMBER NOT NULL,
    bolsillo_id NUMBER,
    tipo VARCHAR2(7) NOT NULL,
    valor NUMBER(12,0) NOT NULL,
    concepto VARCHAR2(200) NOT NULL,
    origen VARCHAR2(20) NOT NULL,
    referencia VARCHAR2(50),
    categoria VARCHAR2(45),
    usuario_id NUMBER NOT NULL,
    anulado NUMBER(1) DEFAULT 0 NOT NULL,
    motivo_anulacion VARCHAR2(500),
    CONSTRAINT pk_movimientos_banco PRIMARY KEY (id),
    CONSTRAINT fk_movbanco_banco FOREIGN KEY (banco_id) REFERENCES bancos (id),
    CONSTRAINT fk_movbanco_bolsillo FOREIGN KEY (bolsillo_id) REFERENCES bolsillos (id),
    CONSTRAINT fk_movbanco_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_movbanco_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_movbanco_valor CHECK (valor > 0),
    CONSTRAINT ck_movbanco_origen CHECK (origen IN ('PAGO', 'MANUAL', 'TRASLADO_CAJA', 'TRASLADO_BANCO')),
    CONSTRAINT ck_movbanco_anulado CHECK (anulado IN (0, 1))
);

CREATE INDEX ix_movbanco_saldo ON movimientos_banco (banco_id, bolsillo_id, anulado);
CREATE INDEX ix_movbanco_ref ON movimientos_banco (origen, referencia);
CREATE INDEX ix_movbanco_fecha ON movimientos_banco (fecha);

-- Traslados entre caja y banco: se distinguen para no contarlos como ingreso/gasto.
ALTER TABLE ingresos_caja ADD (es_traslado NUMBER(1) DEFAULT 0 NOT NULL);
ALTER TABLE salidas_caja ADD (es_traslado NUMBER(1) DEFAULT 0 NOT NULL);

INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, permisos.codigo
FROM perfiles pf
JOIN usuarios u ON u.id = pf.usuario_id
CROSS JOIN (
    SELECT 'ver_bancos' AS codigo FROM dual UNION ALL
    SELECT 'gestionar_bancos' FROM dual
) permisos
WHERE u.rol = 'admin';

GRANT SELECT, INSERT, UPDATE ON CEA_APP.BANCOS TO CEA_WEB;
GRANT SELECT, INSERT, UPDATE ON CEA_APP.BOLSILLOS TO CEA_WEB;
GRANT SELECT, INSERT, UPDATE ON CEA_APP.MOVIMIENTOS_BANCO TO CEA_WEB;

COMMIT;