-- MIS CUENTAS del CEA · cuentas fijas de cada mes (arriendo, luz, agua, nómina…) y permiso nuevo.
-- Ejecutar UNA sola vez, conectado como CEA_APP, como script (F5 en SQL Developer).

SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    cantidad NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CEA_APP' THEN
        RAISE_APPLICATION_ERROR(-20901, 'Conéctate como CEA_APP para ejecutar esta migración.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM all_users WHERE username = 'CEA_WEB';
    IF cantidad = 0 THEN
        RAISE_APPLICATION_ERROR(-20902, 'No existe el usuario de aplicación CEA_WEB.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tables
    WHERE table_name IN ('USUARIOS', 'PERFILES', 'PERFIL_PERMISOS');
    IF cantidad <> 3 THEN
        RAISE_APPLICATION_ERROR(-20903, 'Aplica primero las migraciones 001-008.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM user_tables WHERE table_name = 'CUENTAS_CEA';
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20904, 'La tabla CUENTAS_CEA ya existe; revisa si la migración ya se aplicó.');
    END IF;

    SELECT COUNT(*) INTO cantidad FROM perfil_permisos WHERE codigo = 'ver_cuentas';
    IF cantidad <> 0 THEN
        RAISE_APPLICATION_ERROR(-20905, 'El permiso ver_cuentas ya existe; revisa si la migración ya se aplicó.');
    END IF;
END;
/

CREATE TABLE cuentas_cea (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(80) NOT NULL,
    categoria VARCHAR2(40) NOT NULL,
    valor NUMBER(12,0) NOT NULL,
    activa NUMBER(1,0) DEFAULT 1 NOT NULL,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_cuentas_cea PRIMARY KEY (id),
    CONSTRAINT ck_cuentas_cea_valor CHECK (valor > 0),
    CONSTRAINT ck_cuentas_cea_activa CHECK (activa IN (0, 1))
);

-- Los administradores existentes ven «Mis cuentas» desde el primer momento.
INSERT INTO perfil_permisos (perfil_id, codigo)
SELECT pf.id, 'ver_cuentas'
FROM perfiles pf
JOIN usuarios u ON u.id = pf.usuario_id
WHERE u.rol = 'admin';

GRANT SELECT, INSERT, UPDATE, DELETE ON CEA_APP.CUENTAS_CEA TO CEA_WEB;

COMMIT;
PROMPT Migración 009 de Mis cuentas aplicada correctamente.
