-- TIENDA · Tablas de la caja, el inventario y las ventas.
-- Ejecutar UNA sola vez, conectado como el usuario de Oracle que creaste para la tienda
-- (no como CEA_APP). Ejecutar como script (F5 en SQL Developer).

CREATE SEQUENCE t_seq_productos START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE SEQUENCE t_seq_ventas START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE t_productos (
    id NUMBER NOT NULL,
    nombre VARCHAR2(80) NOT NULL,
    categoria VARCHAR2(40) DEFAULT 'General' NOT NULL,
    costo NUMBER(12,0) DEFAULT 0 NOT NULL,
    precio NUMBER(12,0) NOT NULL,
    stock NUMBER(10,0) DEFAULT 0 NOT NULL,
    stock_minimo NUMBER(10,0) DEFAULT 0 NOT NULL,
    activo NUMBER(1,0) DEFAULT 1 NOT NULL,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_t_productos PRIMARY KEY (id),
    CONSTRAINT ck_t_prod_precio CHECK (precio > 0),
    CONSTRAINT ck_t_prod_costo CHECK (costo >= 0),
    CONSTRAINT ck_t_prod_stock CHECK (stock >= 0),
    CONSTRAINT ck_t_prod_minimo CHECK (stock_minimo >= 0),
    CONSTRAINT ck_t_prod_activo CHECK (activo IN (0, 1))
);

CREATE INDEX ix_t_productos_activo ON t_productos (activo, categoria, nombre);

CREATE TABLE t_ventas (
    id NUMBER NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    metodo VARCHAR2(20) NOT NULL,
    total NUMBER(12,0) NOT NULL,
    costo_total NUMBER(12,0) NOT NULL,
    recibido NUMBER(12,0) DEFAULT 0 NOT NULL,
    cambio NUMBER(12,0) DEFAULT 0 NOT NULL,
    usuario_id NUMBER NOT NULL,
    usuario_nombre VARCHAR2(100) NOT NULL,
    anulada NUMBER(1,0) DEFAULT 0 NOT NULL,
    motivo_anulacion VARCHAR2(500),
    fecha_anulacion TIMESTAMP,
    anulada_por VARCHAR2(100),
    CONSTRAINT pk_t_ventas PRIMARY KEY (id),
    CONSTRAINT ck_t_ventas_metodo CHECK (metodo IN ('Efectivo', 'Nequi', 'Tarjeta')),
    CONSTRAINT ck_t_ventas_total CHECK (total > 0),
    CONSTRAINT ck_t_ventas_anulada CHECK (anulada IN (0, 1))
);

CREATE INDEX ix_t_ventas_fecha ON t_ventas (fecha);

CREATE TABLE t_venta_items (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    venta_id NUMBER NOT NULL,
    producto_id NUMBER NOT NULL,
    nombre VARCHAR2(80) NOT NULL,
    cantidad NUMBER(6,0) NOT NULL,
    precio NUMBER(12,0) NOT NULL,
    costo NUMBER(12,0) NOT NULL,
    CONSTRAINT pk_t_venta_items PRIMARY KEY (id),
    CONSTRAINT fk_t_items_venta FOREIGN KEY (venta_id) REFERENCES t_ventas (id),
    CONSTRAINT fk_t_items_producto FOREIGN KEY (producto_id) REFERENCES t_productos (id),
    CONSTRAINT ck_t_items_cantidad CHECK (cantidad > 0)
);

CREATE INDEX ix_t_items_venta ON t_venta_items (venta_id);

CREATE INDEX ix_t_items_producto ON t_venta_items (producto_id);

-- Historial de cada entrada y salida del inventario (quién, cuándo y cuánto quedó).
CREATE TABLE t_movimientos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    producto_id NUMBER NOT NULL,
    tipo VARCHAR2(12) NOT NULL,
    cantidad NUMBER(10,0) NOT NULL,
    stock_resultante NUMBER(10,0) NOT NULL,
    venta_id NUMBER,
    usuario_id NUMBER,
    nota VARCHAR2(200),
    CONSTRAINT pk_t_movimientos PRIMARY KEY (id),
    CONSTRAINT fk_t_mov_producto FOREIGN KEY (producto_id) REFERENCES t_productos (id),
    CONSTRAINT ck_t_mov_tipo CHECK (tipo IN ('INICIAL', 'ENTRADA', 'VENTA', 'ANULACION', 'AJUSTE'))
);

CREATE INDEX ix_t_mov_producto ON t_movimientos (producto_id, fecha);

-- Preferencias para calcular la ganancia neta (gastos fijos, comisión, impuesto, reinversión).
CREATE TABLE t_ajustes (
    clave VARCHAR2(40) NOT NULL,
    valor VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_t_ajustes PRIMARY KEY (clave)
);

COMMIT;

