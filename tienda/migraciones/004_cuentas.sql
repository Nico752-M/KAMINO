-- TIENDA · Cuentas del negocio (gastos fijos de cada mes: luz, agua, arriendo, nómina…).
-- Ejecutar UNA sola vez, conectado como el usuario de Oracle de la tienda (CEA_JAMES), como script.

CREATE TABLE t_cuentas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(80) NOT NULL,
    categoria VARCHAR2(40) NOT NULL,
    valor NUMBER(12,0) NOT NULL,
    activa NUMBER(1,0) DEFAULT 1 NOT NULL,
    creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_t_cuentas PRIMARY KEY (id),
    CONSTRAINT ck_t_cuentas_valor CHECK (valor > 0),
    CONSTRAINT ck_t_cuentas_activa CHECK (activa IN (0, 1))
);

COMMIT;
